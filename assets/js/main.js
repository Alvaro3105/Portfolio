let lang = localStorage.getItem("portfolio-lang") || "pt";
let terminalIndex = 0;
let typingTimer;

const $ = (selector, scope = document) => scope.querySelector(selector);
const $$ = (selector, scope = document) => [...scope.querySelectorAll(selector)];

function applyLanguage(nextLang) {
  lang = nextLang;
  localStorage.setItem("portfolio-lang", lang);
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  $$('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });
  const switcher = $("#langSwitch");
  if (switcher) switcher.textContent = lang === "pt" ? "EN" : "PT";
  const certBtn = $("#certToggle");
  if (certBtn) certBtn.textContent = document.body.classList.contains("show-all-certs") ? translations[lang].showLess : translations[lang].showAll;
  startTyping();
}

function typeText(text, target) {
  clearTimeout(typingTimer);
  target.textContent = "";
  let i = 0;
  function tick() {
    target.textContent = text.slice(0, i++);
    if (i <= text.length) typingTimer = setTimeout(tick, 34);
  }
  tick();
}

function startTyping() {
  const target = $("#typedText");
  if (!target) return;
  const lines = translations[lang].terminal;
  terminalIndex %= lines.length;
  typeText(lines[terminalIndex], target);
}

function cycleTerminal() {
  const lines = translations[lang].terminal;
  terminalIndex = (terminalIndex + 1) % lines.length;
  startTyping();
}

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: .12 });

$$('.reveal').forEach((el) => observer.observe(el));

window.addEventListener("scroll", () => {
  $("#siteHeader")?.classList.toggle("scrolled", window.scrollY > 20);
});

$("#langSwitch")?.addEventListener("click", () => applyLanguage(lang === "pt" ? "en" : "pt"));

$("#menuBtn")?.addEventListener("click", () => {
  const menu = $("#navLinks");
  const open = menu.classList.toggle("open");
  $("#menuBtn").setAttribute("aria-expanded", String(open));
});

$$('#navLinks a').forEach((link) => link.addEventListener("click", () => {
  $("#navLinks")?.classList.remove("open");
  $("#menuBtn")?.setAttribute("aria-expanded", "false");
}));

$("#certToggle")?.addEventListener("click", () => {
  const active = document.body.classList.toggle("show-all-certs");
  $$('.hidden-cert').forEach((card) => card.style.display = active ? "block" : "none");
  $("#certToggle").textContent = active ? translations[lang].showLess : translations[lang].showAll;
});

const resumeLink = $('[data-i18n="resume"]');
if (resumeLink) resumeLink.href = "curriculo.html";

$("#year").textContent = new Date().getFullYear();
applyLanguage(lang);
setInterval(cycleTerminal, 4200);
